/*
===============================================================================
Gold Layer Quality Checks
===============================================================================
Run after creating the Gold views. These are read-only diagnostic queries.
Returned rows are findings to investigate, not automatic failures: NULL or
'n/a' values and repeated-looking sales lines may be valid source outcomes.
===============================================================================
*/

-- ====================================================================
-- Customer dimension
-- ====================================================================
-- Surrogate keys are generated by ROW_NUMBER in the view; retain this check,
-- and also check customer_id, the business key used to join sales.
SELECT customer_key, COUNT(*) AS row_count
FROM gold.dim_customers
GROUP BY customer_key
HAVING customer_key IS NULL OR COUNT(*) > 1;

SELECT customer_id, COUNT(*) AS row_count
FROM gold.dim_customers
GROUP BY customer_id
HAVING customer_id IS NULL OR COUNT(*) > 1;

-- Missing customer attributes and values outside the standardization performed
-- in Silver should be reviewed. Country is not limited to a fixed value list.
SELECT *
FROM gold.dim_customers
WHERE customer_number IS NULL OR TRIM(customer_number) = ''
   OR first_name IS NULL OR TRIM(first_name) = ''
   OR last_name IS NULL OR TRIM(last_name) = ''
   OR country IS NULL OR TRIM(country) = ''
   OR birthdate IS NULL
   OR create_date IS NULL
   OR marital_status IS NULL
   OR marital_status NOT IN ('Single', 'Married', 'n/a')
   OR gender IS NULL
   OR gender NOT IN ('Female', 'Male', 'n/a');

-- Show distinct country values rather than assuming an exhaustive country list.
SELECT DISTINCT country
FROM gold.dim_customers
ORDER BY country;

-- ====================================================================
-- Product dimension
-- ====================================================================
-- Check generated surrogate keys and product_number, which is the business
-- key used to join sales. Multiple historical product versions are filtered
-- from this view; duplicates among current rows need investigation.
SELECT product_key, COUNT(*) AS row_count
FROM gold.dim_products
GROUP BY product_key
HAVING product_key IS NULL OR COUNT(*) > 1;

SELECT product_number, COUNT(*) AS row_count
FROM gold.dim_products
GROUP BY product_number
HAVING product_number IS NULL OR COUNT(*) > 1;

-- Missing descriptive attributes and standardized product-line values can
-- indicate incomplete source enrichment or unexpected source data.
SELECT *
FROM gold.dim_products
WHERE product_number IS NULL OR TRIM(product_number) = ''
   OR product_name IS NULL OR TRIM(product_name) = ''
   OR category_id IS NULL OR TRIM(category_id) = ''
   OR category IS NULL OR TRIM(category) = ''
   OR subcategory IS NULL OR TRIM(subcategory) = ''
   OR maintenance IS NULL OR TRIM(maintenance) = ''
   OR cost IS NULL OR cost < 0
   OR product_line IS NULL
   OR product_line NOT IN ('Mountain', 'Road', 'Other Sales', 'Touring', 'n/a')
   OR start_date IS NULL;

-- maintenance comes directly from the ERP category table. List actual values
-- for review instead of assuming a business-approved value set.
SELECT DISTINCT maintenance
FROM gold.dim_products
ORDER BY maintenance;

-- ====================================================================
-- Fact-to-dimension matching and join cardinality
-- ====================================================================
-- The Gold fact view should have customer and product keys for matched rows.
-- NULL keys identify sales details that did not find a current dimension row.
SELECT
    order_number,
    product_key,
    customer_key,
    order_date,
    shipping_date,
    due_date,
    sales_amount,
    quantity,
    price
FROM gold.fact_sales
WHERE product_key IS NULL OR customer_key IS NULL;

-- A LEFT JOIN keeps all Silver sales rows, but duplicate dimension business
-- keys can multiply them. Compare counts; a difference needs investigation.
SELECT
    (SELECT COUNT_BIG(*) FROM silver.crm_sales_details) AS silver_sales_row_count,
    (SELECT COUNT_BIG(*) FROM gold.fact_sales) AS gold_fact_row_count,
    (SELECT COUNT_BIG(*) FROM gold.fact_sales)
      - (SELECT COUNT_BIG(*) FROM silver.crm_sales_details) AS row_count_difference;

-- Show any duplicate complete fact-view rows. Repeated values may be legitimate
-- separate source lines because the source has no separate line identifier here.
SELECT
    order_number,
    product_key,
    customer_key,
    order_date,
    shipping_date,
    due_date,
    sales_amount,
    quantity,
    price,
    COUNT(*) AS duplicate_count
FROM gold.fact_sales
GROUP BY
    order_number,
    product_key,
    customer_key,
    order_date,
    shipping_date,
    due_date,
    sales_amount,
    quantity,
    price
HAVING COUNT(*) > 1;

-- ====================================================================
-- Fact sales values and dates
-- ====================================================================
-- Non-positive or missing measures are suspicious for sales detail, but
-- review against source meaning before treating any row as invalid.
SELECT *
FROM gold.fact_sales
WHERE sales_amount IS NULL OR sales_amount <= 0
   OR quantity IS NULL OR quantity <= 0
   OR price IS NULL OR price <= 0;

-- Investigate sales amounts that do not equal quantity times price. Values
-- use integer columns in this model, so the comparison is exact integer math.
SELECT
    order_number,
    sales_amount,
    quantity,
    price,
    CAST(quantity AS decimal(19, 0))
        * CAST(price AS decimal(19, 0)) AS calculated_sales
FROM gold.fact_sales
WHERE sales_amount IS NOT NULL
  AND quantity IS NOT NULL
  AND price IS NOT NULL
  AND CAST(sales_amount AS decimal(19, 0))
      <> CAST(quantity AS decimal(19, 0))
         * CAST(price AS decimal(19, 0));

-- Missing dates and inconsistent chronology may reflect source gaps or
-- source-system rules; review the affected orders rather than auto-failing.
SELECT order_number, order_date, shipping_date, due_date
FROM gold.fact_sales
WHERE order_date IS NULL OR shipping_date IS NULL OR due_date IS NULL
   OR (order_date IS NOT NULL AND shipping_date IS NOT NULL
       AND order_date > shipping_date)
   OR (order_date IS NOT NULL AND due_date IS NOT NULL
       AND order_date > due_date)
   OR (shipping_date IS NOT NULL AND due_date IS NOT NULL
       AND shipping_date > due_date);
